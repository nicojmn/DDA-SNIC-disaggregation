#!/usr/bin/env python3
"""
csv_analyzer.py — Interactive CSV statistics analyzer for benchmark results
(throughput / IOPS grouped by ENGINE and SIZE, with CSV and LaTeX export).

Attribution:
    This file was generated by an AI assistant (KIMI K3). I reviewed,
    tested, and improved the generated code.
"""

import os
import pandas as pd
import numpy as np
import questionary
from questionary import Style

custom_style = Style(
    [
        ("qmark", "fg:#00c8c8 bold"),
        ("question", "bold"),
        ("pointer", "fg:#00c8c8 bold"),
        ("highlighted", "fg:#00c8c8 bold"),
        ("selected", "fg:#27ae60"),
    ]
)

# ---- available statistics (pick one or more) ----
STATS_FUNCS = {
    "count": lambda g, v: g[v].count(),
    "mean": lambda g, v: g[v].mean(),
    "variance": lambda g, v: g[v].var(),
    "std_dev": lambda g, v: g[v].std(),
    "min": lambda g, v: g[v].min(),
    "median": lambda g, v: g[v].median(),
    "max": lambda g, v: g[v].max(),
    "sum": lambda g, v: g[v].sum(),
    "cv_%": lambda g, v: g[v].std() / g[v].mean() * 100,
}

# stats whose values are in bytes -> human-readable
BYTE_STATS = {"mean", "std_dev", "min", "median", "max", "sum"}

DEFAULT_STATS = ["mean", "std_dev", "min", "median", "max"]


# ---------------- Unit helpers ----------------


def human_bytes(n):
    """Format a byte value with the appropriate SI unit (B/s, kB/s, ...)."""
    if n is None or (isinstance(n, float) and np.isnan(n)):
        return "n/a"
    sign = "-" if n < 0 else ""
    n = abs(float(n))
    for unit in ["B/s", "kB/s", "MB/s", "GB/s", "TB/s"]:
        if n < 1000 or unit == "TB/s":
            return f"{sign}{n:,.2f} {unit}"
        n /= 1000


def human_iops(n):
    """Format IOPS with SI k/M/G suffixes."""
    if n is None or (isinstance(n, float) and np.isnan(n)):
        return "n/a"
    n = float(n)
    for unit in ["", "k", "M", "G"]:
        if abs(n) < 1000 or unit == "G":
            return f"{n:,.2f} {unit}IOPS"
        n /= 1000


def parse_size(v):
    """Parse an IO size to bytes using SI units (k = 1000, M = 1000**2, ...).
    Handles ints/floats and strings like '4096', '4k', '4K', '4KB', '1M'.
    Returns NaN if unparseable."""
    if isinstance(v, (int, float)) and not pd.isna(v):
        return float(v)
    s = str(v).strip().lower().replace(" ", "")
    mult = 1
    for suffix, m in [
        ("kb", 1000),
        ("mb", 1000**2),
        ("gb", 1000**3),
        ("k", 1000),
        ("m", 1000**2),
        ("g", 1000**3),
        ("b", 1),
    ]:
        if s.endswith(suffix):
            mult = m
            s = s[: -len(suffix)]
            break
    try:
        return float(s) * mult
    except ValueError:
        return np.nan


# ---------------- Display formatting ----------------


def format_for_display(result: pd.DataFrame, value_is_iops=False) -> pd.DataFrame:
    """Format values as human-readable strings for display."""
    disp = result.copy()
    for col in disp.columns:
        if col in BYTE_STATS:
            disp[col] = disp[col].apply(human_iops if value_is_iops else human_bytes)
        elif col == "variance":
            disp[col] = disp[col].apply(
                lambda v: f"{v:.3e} IOPS²" if value_is_iops else f"{v:.3e} B²"
            )
        elif col == "cv_%":
            disp[col] = disp[col].apply(lambda v: f"{v:.2f} %")
    return disp


# ---------------- LaTeX export ----------------


def escape_latex(s):
    """Escape LaTeX special characters."""
    return (
        str(s)
        .replace("&", "\\&")
        .replace("%", "\\%")
        .replace("_", "\\_")
        .replace("#", "\\#")
    )


def format_latex_value(name, v, value_is_iops=False):
    """Format a single stat value for LaTeX output."""
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "n/a"
    if name in BYTE_STATS:
        if value_is_iops:
            return human_iops(v).replace(" ", "")
        return human_bytes(v).replace(" ", "")
    if name == "variance":
        return f"{v:.3e}"
    if name == "cv_%":
        return f"{v:.2f}\\%"
    return str(v)


def to_latex(result: pd.DataFrame, group_cols, value_is_iops=False) -> str:
    """Generate the LaTeX table body (rows between \\toprule and \\bottomrule).

    Inserts a \\midrule whenever the ENGINE (first group column) changes.
    """
    lines = []
    prev_engine = object()
    engine_col = group_cols[0] if group_cols else None

    # reset_index so group columns are accessible as regular columns
    flat = result.reset_index()

    for _, row in flat.iterrows():
        engine = row[engine_col] if engine_col else None
        if engine != prev_engine:
            if lines:
                lines.append("\\midrule")
            prev_engine = engine

        cells = [escape_latex(row[c]) for c in group_cols]
        cells += [format_latex_value(c, row[c], value_is_iops) for c in result.columns]
        # make the engine cell bold
        if group_cols:
            cells[0] = f"\\textbf{{{cells[0]}}}"
        lines.append(" & ".join(cells) + " \\\\")

    return "\n".join(lines)


# ---------------- File browser ----------------


def browse_csv(start_dir="."):
    cwd = os.path.abspath(start_dir)
    while True:
        entries = sorted(os.listdir(cwd))
        dirs = [f"[D] {e}" for e in entries if os.path.isdir(os.path.join(cwd, e))]
        csvs = [f"    {e}" for e in entries if e.lower().endswith(".csv")]
        choices = [".. (up)"] + dirs + csvs + ["✖ Cancel"]

        pick = questionary.select(
            f"Select CSV file  ({cwd})",
            choices=choices,
            style=custom_style,
        ).ask()

        if pick is None or pick == "✖ Cancel":
            return None
        if pick == ".. (up)":
            cwd = os.path.dirname(cwd)
        elif pick.startswith("[D] "):
            cwd = os.path.join(cwd, pick[4:])
        else:
            return os.path.join(cwd, pick.strip())


def main():
    # 1) Pick CSV file
    path = browse_csv()
    if not path:
        print("Cancelled.")
        return

    df = pd.read_csv(path)
    print(f"\nLoaded {len(df)} rows from {path}")

    # 2) Value column
    numeric_cols = [c for c in df.columns if pd.api.types.is_numeric_dtype(df[c])]
    value_col = questionary.select(
        "Value column:",
        choices=numeric_cols,
        default="y_BANDWIDTH" if "y_BANDWIDTH" in numeric_cols else numeric_cols[0],
        style=custom_style,
    ).ask()

    # 2b) Block size for IOPS: parsed from a 'bs-<SIZE>' path component
    #     (SI units, k = 1000). Falls back to manual entry.
    iops_available = False
    df["IOPS"] = np.nan

    bs_bytes = None
    for part in path.split(os.sep):
        if part.lower().startswith("bs-"):
            bs_bytes = parse_size(part[3:])
            break

    if bs_bytes is not None:
        print(f"Block size from path: {int(bs_bytes)} B")
    else:
        raw = questionary.text(
            "Block size (SI, e.g. 4000, 4k):",
            validate=lambda s: not np.isnan(parse_size(s)) or "Unparseable size",
            style=custom_style,
        ).ask()
        if raw:
            bs_bytes = parse_size(raw)

    if bs_bytes is not None and bs_bytes > 0:
        df["IOPS"] = df[value_col] / bs_bytes
        bad = int(df["IOPS"].isna().sum())
        if bad:
            print(f"Warning: {bad} rows -> IOPS = NaN")
        iops_available = True

    # 3) Group-by (auto: ENGINE, SIZE if present)
    group_cols = [c for c in ("ENGINE", "SIZE") if c in df.columns]
    if not group_cols:
        group_cols = [
            questionary.select(
                "Group by column:",
                choices=[c for c in df.columns if c != value_col],
                style=custom_style,
            ).ask()
        ]
    print(f"Grouping by: {group_cols}")

    # 4) Pick ONE OR MORE statistics
    chosen = questionary.checkbox(
        "Select statistics (space = toggle, enter = confirm):",
        choices=[
            questionary.Choice(name, checked=(name in DEFAULT_STATS))
            for name in STATS_FUNCS
        ],
        validate=lambda a: "Select at least one statistic!" if not a else True,
        style=custom_style,
    ).ask()
    if not chosen:
        return

    # 5) Compute (raw numeric values)
    grouped = df.groupby(group_cols)
    result = pd.DataFrame(
        {name: STATS_FUNCS[name](grouped, value_col) for name in chosen}
    )

    # 5b) IOPS per group (per-run IOPS aggregated with the same statistics)
    iops_result = None
    if iops_available:
        iops_result = pd.DataFrame(
            {name: STATS_FUNCS[name](grouped, "IOPS") for name in chosen}
        )

    # 6) Display human-readable
    print("\n" + "=" * 70)
    print(f"Throughput stats by {group_cols}:")
    print(format_for_display(result).to_string())

    if iops_result is not None:
        print("-" * 70)
        print(f"IOPS stats by {group_cols} (per-run IOPS aggregated):")
        print(format_for_display(iops_result, value_is_iops=True).to_string())
    print("=" * 70)

    # 6b) Per-engine summary: mean throughput and mean IOPS
    eng = None
    if "ENGINE" in df.columns:
        eng = df.groupby("ENGINE").agg(
            runs=(value_col, "count"),
            mean_throughput_Bs=(value_col, "mean"),
            std_throughput_Bs=(value_col, "std"),
        )
        if iops_available:
            eng["mean_IOPS"] = df.groupby("ENGINE")["IOPS"].mean()
            eng["std_IOPS"] = df.groupby("ENGINE")["IOPS"].std()
        disp = eng.copy()
        disp["mean_throughput_Bs"] = disp["mean_throughput_Bs"].apply(human_bytes)
        disp["std_throughput_Bs"] = disp["std_throughput_Bs"].apply(human_bytes)
        if "mean_IOPS" in disp.columns:
            disp["mean_IOPS"] = disp["mean_IOPS"].apply(human_iops)
            disp["std_IOPS"] = disp["std_IOPS"].apply(human_iops)
        print("\nPer-engine summary:")
        print(disp.to_string())

    # 7) Optional save
    if questionary.confirm("Save results?", default=False, style=custom_style).ask():
        fmt = questionary.select(
            "Format:",
            choices=[
                "CSV (raw)",
                "LaTeX tabularx",
                "Both",
                "Per-run CSV (with IOPS)",
                "Engine summary CSV",
            ],
            style=custom_style,
        ).ask()

        if fmt in ("CSV (raw)", "Both"):
            out = questionary.text(
                "CSV output file:", default="stats_output.csv", style=custom_style
            ).ask()
            if out:
                result.to_csv(out)
                if iops_result is not None:
                    iops_result.to_csv(out.replace(".csv", "") + "_iops.csv")
                    print(
                        f"Saved -> {out} and IOPS -> {out.replace('.csv', '')}_iops.csv"
                    )
                else:
                    print(f"Saved -> {out} (raw byte values)")

        if fmt in ("LaTeX tabularx", "Both"):
            out = questionary.text(
                "LaTeX output file:", default="stats_output.tex", style=custom_style
            ).ask()
            if out:
                body = to_latex(result, group_cols)
                if iops_result is not None:
                    body += "\n\\midrule\\midrule\n% IOPS (per-run, aggregated)\n"
                    body += to_latex(iops_result, group_cols, value_is_iops=True)
                with open(out, "w") as f:
                    f.write(body + "\n")
                print(f"Saved -> {out}")
                print(
                    "\n--- LaTeX table body "
                    "(paste between \\toprule and \\bottomrule) ---"
                )
                print(body)

        if fmt == "Per-run CSV (with IOPS)":
            out = questionary.text(
                "Output file:", default="runs_with_iops.csv", style=custom_style
            ).ask()
            if out:
                df.to_csv(out, index=False)
                print(f"Saved -> {out}")

        if fmt == "Engine summary CSV":
            if eng is None:
                print("No ENGINE column -> engine summary not available.")
            else:
                out = questionary.text(
                    "Output file:", default="engine_summary.csv", style=custom_style
                ).ask()
                if out:
                    eng.to_csv(out)
                    print(f"Saved -> {out}")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\nAborted.")
